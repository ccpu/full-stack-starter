import { useEffect, useState } from 'react';

import './Options.css';

interface ChromeMessage {
  type: string;
  count?: number;
}

interface StorageResult {
  count?: number;
}

export const Options = () => {
  const [countSync, setCountSync] = useState(0);
  const link = 'https://github.com/guocaoyi/create-chrome-ext';

  useEffect(() => {
    chrome.storage.sync.get(['count'], (result: StorageResult) => {
      setCountSync(result.count ?? 0);
    });

    chrome.runtime.onMessage.addListener((request: ChromeMessage) => {
      if (request.type === 'COUNT') {
        setCountSync(request.count ?? 0);
      }
    });
  }, []);

  return (
    <main>
      <h3>Options Page</h3>
      <h4>Count from Popup: {countSync}</h4>
      <a href={link} target="_blank" rel="noreferrer">
        generated by create-chrome-ext
      </a>
    </main>
  );
};

export default Options;
