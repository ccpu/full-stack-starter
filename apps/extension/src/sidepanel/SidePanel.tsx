import { useEffect, useState } from "react";

interface ChromeMessage {
  type: string;
  count?: number;
}

interface StorageResult {
  count?: number;
}

export const SidePanel = () => {
  const [countSync, setCountSync] = useState(0);
  const link = "https://github.com/guocaoyi/create-chrome-ext";

  useEffect(() => {
    chrome.storage.sync.get(["count"], (result: StorageResult) => {
      setCountSync(result.count ?? 0);
    });

    chrome.runtime.onMessage.addListener((request: ChromeMessage) => {
      if (request.type === "COUNT") {
        setCountSync(request.count ?? 0);
      }
    });
  }, []);

  return (
    <main className="mx-auto p-4 text-center">
      <h3 className="my-8 text-4xl font-extralight uppercase leading-5 text-primary">
        SidePanel Page
      </h3>
      <h4 className="mb-2">Count from Popup: {countSync}</h4>
      <a
        href={link}
        target="_blank"
        className="m-2 text-xs text-foreground no-underline hover:underline"
      >
        generated by create-chrome-ext
      </a>
    </main>
  );
};

export default SidePanel;
