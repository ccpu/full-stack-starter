import { ReactNativeComponent } from '@internal/ui';
import { useEffect, useState } from 'react';

const ONE_SECOND_MS = 1000;
const TIME_PADDING_LENGTH = 2;

export function NewTab() {
  const getTime = () => {
    const date = new Date();
    const hour = String(date.getHours()).padStart(TIME_PADDING_LENGTH, '0');
    const minute = String(date.getMinutes()).padStart(TIME_PADDING_LENGTH, '0');
    return `${hour}:${minute}`;
  };

  const [time, setTime] = useState(() => getTime());
  const link = 'https://github.com/guocaoyi/create-chrome-ext';

  useEffect(() => {
    const intervalId = setInterval(() => {
      setTime(getTime());
    }, ONE_SECOND_MS);

    return () => {
      clearInterval(intervalId);
    };
  }, []);

  return (
    <section className="flex min-h-screen flex-col items-center">
      <h1 className="mb-2 text-8xl font-bold tracking-tight text-primary drop-shadow-lg">
        {time}
      </h1>
      <a
        href={link}
        target="_blank"
        className="mb-6 text-sm text-foreground hover:underline"
        rel="noreferrer"
      >
        generated by create-chrome-ext
      </a>
      <ReactNativeComponent />
    </section>
  );
}

export default NewTab;
